    // Lowercase (5-row x-height, baseline-aligned with the caps above):
    // only the letters actually used in the skin so far. Everything else
    // still falls back to its capital via drawText.
    "m": [0,0b11010,0b10101,0b10101,0b10101,0b10101],
    "o": [0,0b01110,0b10001,0b10001,0b10001,0b01110],
